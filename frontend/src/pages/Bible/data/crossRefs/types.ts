// 연결 구절 데이터 타입 — 성경이 성경을 가리키는 자리.
//  - quote: 신약이 구약을 인용한 곳 ("기록된 바", "선지자로 하신 말씀을 이루려 하심이라")
//  - parallel: 같은 사건·말씀을 여러 복음서가 기록한 평행 본문
// 참조 문자열은 "책:장:절" 또는 "책:장:절-끝절"(같은 장 안) — 예: '40:1:23', '41:4:35-41'.
// 정적 데이터이며 백엔드에 저장하지 않는다. 역방향(구약 → 신약 인용)은 로더가 뒤집어 만든다.

/** [신약 인용 위치, 구약 원문 위치, 짧은 설명(선택, ~20자)] */
export type QuoteRow = readonly [from: string, to: string, note?: string]

/** 같은 이야기를 담은 본문 묶음 — 2~4개 참조, 첫 칸은 짧은 제목(~12자) */
export type ParallelGroup = readonly [title: string, ...refs: string[]]
