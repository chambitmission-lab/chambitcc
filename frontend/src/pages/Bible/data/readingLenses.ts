const LENS_BY_ID = Object.fromEntries(READING_LENSES.map((l) => [l.id, l])) as Record<ReadingLensId, ReadingLens>

export const isReadingLensId = (v: unknown): v is ReadingLensId =>
  typeof v === 'string' && v in LENS_BY_ID

/** 회차 기본 렌즈 — 2독=그리스도, 3독=언약, 4독부터=기도. 1독은 흐름 */
export const defaultLensFor = (cycleNo: number): ReadingLensId =>
  cycleNo <= 1 ? 'story' : cycleNo === 2 ? 'christ' : cycleNo === 3 ? 'covenant' : 'prayer'

export const resolveLens = (cycleNo: number, saved: string | null | undefined): ReadingLens =>
  LENS_BY_ID[isReadingLensId(saved) ? saved : defaultLensFor(cycleNo)]

