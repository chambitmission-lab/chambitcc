/** 이 장에 띄울 렌즈 질문 — 장르의 세 질문을 장 번호로 돌린다 */
export const lensQuestion = (lens: ReadingLensId, bookNumber: number, chapter: number): string => {
  const genre = getBookGenre(bookNumber).id as GenreId
  const list = QUESTIONS[lens][genre] ?? QUESTIONS[lens].gospels
  return list[(Math.max(1, chapter) - 1) % list.length]
}
