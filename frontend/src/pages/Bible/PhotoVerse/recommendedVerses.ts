/** 하루 단위로 순환하는 오늘의 말씀 — 인트로 예시 카드와 피커의 피처드 카드가 같은 절을 보여준다 */
export const getTodayRecommended = (nowMs: number): PickedVerse =>
  RECOMMENDED[Math.floor(nowMs / 86_400_000) % RECOMMENDED.length]
