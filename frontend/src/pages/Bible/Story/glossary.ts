// {{용어}} 또는 {{표시어|용어}} 마크업을 조각으로 분해.
// 용어가 사전에 없으면 일반 텍스트로 강등된다(콘텐츠 오타 방어).
export interface TextSegment {
  text: string
  term?: string // GLOSSARY 키
}

export const parseGlossaryText = (text: string): TextSegment[] => {
  const segments: TextSegment[] = []
  const re = /\{\{([^{}|]+)(?:\|([^{}]+))?\}\}/g
  let last = 0
  let m: RegExpExecArray | null
  while ((m = re.exec(text)) !== null) {
    if (m.index > last) segments.push({ text: text.slice(last, m.index) })
    const display = m[1]
    const key = m[2] ?? m[1]
    if (GLOSSARY[key]) segments.push({ text: display, term: key })
    else segments.push({ text: display })
    last = m.index + m[0].length
  }
  if (last < text.length) segments.push({ text: text.slice(last) })
  return segments
}
